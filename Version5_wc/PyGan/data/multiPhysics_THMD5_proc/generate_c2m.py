        "* Update : 09/06/2025 : generated automatically by 'generate_c2m.py'\n"
        "* Input data :\n" 
        "*  -Fmap : fuel map with local parameters to be modified/set\n"
        "*  -THData : LCM object with entries ['TFuelList', 'TCoolList', 'DCoolList'] defining material properties \n"
        "*  -Nz : number of axial nodes (NZ)\n"
        "*--------------\n"    
        "* INPUT - OUTPUT LCM data / parameters definition/recovery\n"
        "*--------------\n"
        "PARAMETER  Fmap THData ::\n" 
        "::: LINKED_LIST Fmap THData ; ;\n"
