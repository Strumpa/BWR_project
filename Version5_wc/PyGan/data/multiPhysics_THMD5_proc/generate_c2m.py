# Varying the axial mesh size is "slightly" annoying in CLE-2000, with lack of efficient use of what it can bring.
# From a user perspective, it is error prone and quite tedious.
# The idea is to automate the creation of c2m files for different axial mesh sizes (NZ) in a given range (nz max = 200).
# This needs to be performed for all procedures where axial heterogeneity is involved :  
#                   - GeoCore.c2m (define core geometry)
#                   - SetFMap.c2m (define fuel map)
#                   - SetLocPara.c2m (set local parameters in fuel map)
#                   - solNeutro.c2m (solve neutron diffusion) --> need to interpolate XS on axially varying properties.
#                       --> separate interpolation step from solNeutro.c2m and create interpolateXS.c2m

