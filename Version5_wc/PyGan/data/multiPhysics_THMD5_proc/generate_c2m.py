# interpolateXS functions
def define_mixes_with_interpolation(nz):
    """
    Define the list of mixes with interpolation for the interpolateXS procedure.
    """
    mixes = [f"MIX {i} INST-BURN SET 'TFuel' MAP SET 'TCool' MAP SET 'DCool' MAP ENDMIX" for i in range(1, nz + 1)]
    return "\n".join(mixes)

def fill_interpolateXS_template(nz, interp_opt="LINEAR", proc_name="InterpXS"):
    """
    Fill template for the interpolateXS procedure for a given number of axial nodes (nz).
    This procedure interpolates cross-sections on axially varying properties.
    interp_opt : interpolation option, can be 'LINEAR' or 'CUBIC', default is 'LINEAR'.
    """
    interpolateXS_template = (
        "* Procedure : InterpXS.c2m\n"
        "* Purpose : Interpolate cross-sections on axially varying properties\n"
        "* Author : R. Guasch\n"
        "* Date : 09/06/2025\n"
        "* Input data :\n"
        "*   - Fmap : fuel map with local parameters\n"
        "*   - Cpo : MULTICOMPO hosting XS data to be interpolated\n"
        "*   - MicroF : MULTICOMPO to store interpolated XS data\n"
        "*   - Nz : number of axial nodes (NZ)\n"
        "*--------------\n"    
        "* INPUT - OUTPUT LCM data / parameters definition/recovery\n"
        "*--------------\n"
        "PARAMETER MicroF Fmap Cpo ::\n" 
        "::: LINKED_LIST MicroF Fmap Cpo ; ;\n"
        "INTEGER Nz ;\n"
        ":: >>Nz<< ;\n"
        "*--------------\n"
        "* MODULES definition\n"
        "*--------------\n"
        "MODULE NCR: END: ;\n"
        "*--------------\n"
        "* Variable declaration\n"
        "*--------------\n"

        "ECHO 'Interpolate cross-sections on axially varying properties' ;\n"
        "ECHO 'Interpolation on Nz nodes' Nz ;\n"

        "*--------------\n"
        "* Interpolation of cross-sections on axially varying properties\n"
        "*--------------\n"
        "MicroF := NCR: Cpo Fmap ::\n"
        "EDIT 0\n"
        "NMIX <<Nz>>\n" 
        f"MICRO {interp_opt}\n"
        "TABLE Cpo EDIPARAM\n" 
        f"{define_mixes_with_interpolation(nz)}\n"
        ";\n"
        "END: ;\n"
        "QUIT .\n"
    )
    with open(f"{proc_name}{int(nz)}.c2m", "w") as file:
        file.write(interpolateXS_template)
    file.close()
    return
# Main function to generate c2m files for a range of axial mesh sizes
def generate_c2m_files(nz, nz_max=200, output_dir="c2m_files", exec_case = False):
    """
    Generate c2m files for a range of axial mesh sizes (NZ).
    Args:
        nz (int): NZ value selected by the user.
        nz_max (int): Maximum number of axial nodes.
        output_dir (str): Directory to save the generated c2m files.
        exec_case (bool): If True, execute the generated c2m files. Default is False.
    """
    # check if output directory exists, if not create it
    if not os.path.exists(output_dir):
        os.makedirs(output_dir)
    # check if entry in user selected nz is valid

    if not 1<=nz<= nz_max:
        print(f"No valid NZ values provided. Please provide values between 1 and {nz_max}.")
        return
    
    # Generate GeoCore<(nz)>.c2m files
    
    nfuel = nz  # Assuming a single fuel element for simplicity
    fill_GeoCore_template(nz, nfuel)
    # Move the generated file to the output directory
    os.rename(f"GeoCore{int(nz)}.c2m", os.path.join(output_dir, f"GeoCore{int(nz)}.c2m")) # backup the generated file
    if exec_case: # copy the generated file to the current directory if exec_case is True
        shutil.copy(f"{output_dir}/GeoCore{int(nz)}.c2m", f"GeoCore.c2m")
    
    # Generate SetFMap<nz>.c2m files
    fill_SetFMap_template(nz)
    # Move the generated file to the output directory
    os.rename(f"SetFMap{int(nz)}.c2m", os.path.join(output_dir, f"SetFMap{int(nz)}.c2m"))
    if exec_case: # copy the generated file to the current directory if exec_case is True
        shutil.copy(f"{output_dir}/SetFMap{int(nz)}.c2m", f"SetFMap.c2m")
    
    # Generate SetLocPara<nz>.c2m files
    fill_SetLocPara_template(nz)
    # Move the generated file to the output directory
    os.rename(f"SetLocPara{int(nz)}.c2m", os.path.join(output_dir, f"SetLocPara{int(nz)}.c2m"))
    if exec_case: # copy the generated file to the current directory if exec_case is True
        shutil.copy(f"{output_dir}/SetLocPara{int(nz)}.c2m", f"SetLocPara.c2m")
        
    # Generate interpolateXS<nz>.c2m files
    fill_interpolateXS_template(nz)
    # Move the generated file to the output directory  
    os.rename(f"InterpXS{int(nz)}.c2m", os.path.join(output_dir, f"InterpXS{int(nz)}.c2m"))
    if exec_case:
        shutil.copy(f"{output_dir}/InterpXS{int(nz)}.c2m", f"InterpXS.c2m")
    print(f"Generated c2m files for NZ={nz} and moved to {output_dir}.")



 