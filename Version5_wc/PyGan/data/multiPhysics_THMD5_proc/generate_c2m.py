# SetLocPara functions
def fill_fmap_modification_call(nz):
    """
    Fill call to RESINI that will modify local parameters in fuel map
    """
    fmap_modification_call = (
        "RESINI: Fmap :: EDIT 1\n"
        "BTYPE INST-BURN\n"
        "INST-BVAL CHAN 0.0\n"
        "SET-PARAM 'T-FUEL' BUND\n" 
        f"{format_axial_values('TF', None, nz)}\n" 
        "SET-PARAM 'T-COOL' BUND\n" 
        f"{format_axial_values('TC', None, nz)}\n"  
        "SET-PARAM 'D-COOL' BUND\n" 
        f"{format_axial_values('DC', None, nz)}\n"
        ";\n"
    )
    return fmap_modification_call.strip()

