# Helper functions
def declare_varaibles(variable_name, variable_type, nz):
    """
    Declare variables for axial mesh in the format expected by CLE-2000.
    """
    var_list = [f"{variable_type} {variable_name}{i} ;" for i in range(1, nz + 1)]
    var_lines = [" ".join(var_list[i:i+5]) for i in range(0, nz, 5)]
    return "\n".join(var_lines)

def format_axial_values(variable_name, initial_value, nz):
    """
    Formats lists of axially varying parameters such as axial power distribution, fuel temperature, etc.
    
    Parameters:
    variable_name (str): Name of the variable to be formatted.
    initial_value (real): Initial value for a parameter to be initialized to., if not None is used instead of variable_name formatting.
    nz (int): Number of axial nodes.
    
    Returns:
    str: Formatted string for the axial variation of a parameter throughout the fuel bundles.
    """

    # Format each value to 4 decimal places
    if initial_value is None:
        formatted_values = [f"<<{variable_name}{i}>>" for i in range(1, nz + 1)]
    else:
        formatted_values = [f"<<{initial_value}>>" for i in range(1, nz + 1)]

    # Group into lines of 10 values
    lines = [" ".join(formatted_values[i:i+5]) for i in range(0, len(formatted_values), 5)]

    # Join with newline characters
    return "\n".join(lines)

def recover_variable_from_UTL_list(name_of_variable_holding_UTL_list, key_to_search_UTL_list, variable_name_to_fill, nz):
    """
    For i in nz :
    GREP: name_of_variable_holding_UTL_list :: GETVAL 'key_to_search_UTL_list' i >>variable_name_to_fill<< ;
    """
    lines = []
    for i in range(1, nz + 1):
        lines.append(f"GREP: {name_of_variable_holding_UTL_list} :: GETVAL '{key_to_search_UTL_list}' {i} >>{variable_name_to_fill}{i}<< ;")
    return "\n".join(lines)

def create_axial_mesh(nz):
    lines = ["REAL dz := height Nz / ;", "REAL z1 := dz ;"]
    for i in range(2, nz + 1):
        lines.append(f"REAL z{i} := z{i-1} dz + ;")
    return "\n".join(lines)


# GeoCore functions
def create_GEO(nz):
    mesh_z_list = [f"<<z{i}>>" for i in range(1, nz + 1)]
    mesh_z_lines = [" ".join(mesh_z_list[i:i+10]) for i in range(0, nz, 10)]
    mesh_z = "\n".join(mesh_z_lines)
    planes = "\n".join([f"PLANE {i} {i}" for i in range(1, nz + 1)])

    GEO_call = (
        f"GEO: :: CAR3D 1 1 {nz}\n"
        " X- REFL X+ REFL Y- REFL Y+ REFL Z- VOID Z+ VOID\n"
        " MESHX 0.0 <<pitch>>\n"
        " MESHY 0.0 <<pitch>>\n"
        f" MESHZ 0.0 {mesh_z}\n"
        " MIX\n"
        f"{planes}\n"
        ";\n"
    )
    return GEO_call.strip()

def fill_call_USPLIT(nz,nfuel):
    fuel_mix_numbering_list = [f"{i}" for i in range(1, nz + 1)]
    fuel_mix_numbering_lines = [" ".join(fuel_mix_numbering_list[i:i+10]) for i in range(0, nz, 10)]
    fuel_mix_numbering = "\n".join(fuel_mix_numbering_lines)
    USPLIT_call = (      
        "Geom Matex := USPLIT: Geom :: NGRP 2 MAXR <<MaxR>>\n" 
        f"NMIX {nz} NFUEL {nfuel}\n" 
        f"FMIX {fuel_mix_numbering}\n"
        ";\n" 
    )
    return USPLIT_call.strip()

def fill_GeoCore_template(nz, nfuel, proc_name="GeoCore"):
    """
    fill GeoCore procedrue template for a given number of axial nodes (nz) and number of fuel elements (nfuel).
    """

    GeoCore_c2m_template = (
        "* CLE-2000 Procedure\n" 
        "* Purpose : Generate equivalent core Geometry\n" 
        "* Application : BWR coupled neutronics-TH calculation initialization\n" 
        "* Author(s) : R. Guasch, C. Huet\n"
        "* Automatically generated by 'generate_c2m.py'\n"
        "* Date : 09/06/2025\n"  
        "* Parameters of the procedure\n" 
        "* Benchmark  : BWR-pincell equivalent core geometry\n" 
        "* Input data:\n"
        "*   pitch : assembly/cell pitch\n"
        "*   height : active core height\n" 
        "*   Nz : number of axial nodes (NZ)\n"
        "*--------------\n"    
        "* INPUT - OUTPUT LCM data / parameters definition/recovery\n"
        "*--------------\n"
        "*\n" 
        "PARAMETER       Geom Matex  ::\n"
        "::: LINKED_LIST Geom Matex ; ;\n"

        "*Recover input data\n" 
        "REAL    pitch height Nz ;\n"
        ":: >>pitch<< >>height<< >>Nz<< ;\n"  
        "*--------------\n"    
        "* MODULES definition\n"
        "*--------------\n"
        "MODULE      USPLIT: GEO: END: ;\n"
        "*--------------\n"
        "* Variable definition\n"
        "*--------------\n"
        "INTEGER MaxR := 10000 ;\n"

        "* Axial mesh definition\n"
        f"{create_axial_mesh(nz)}\n"
 
        f"Geom := {create_GEO(nz)}\n"
        f"{fill_call_USPLIT(nz, nfuel)}\n"
    )
    with open(f"{proc_name}{int(nz)}.c2m", "w") as file:
        file.write(GeoCore_c2m_template)
    file.close()
       
    return


