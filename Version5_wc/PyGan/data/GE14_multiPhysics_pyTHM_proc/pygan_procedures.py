### PyGan procedures defining inputs and outputs to c2m DONJON procedures
import lifo
import lcm
import cle2000

def initialize_donjon(fuel_map_lcm_name, matex_lcm_name, track_lcm_name, compo_lcm_names, compo_file_names, init_c2m_name):
    """
    lcm_names : strings representing names of Fuel Map, Material Indexation, Compo and Track (FEM discretization) DONJON LCM objects
    compo_file_name : file name of the multicompo to load cross sections from
    init_c2m_name : name of the initialisation c2m procedure that has been generated by starterDD and should be executed.
    """
    # 3.1) construct the Lifo stack for IniDONJON
    ipLifo1=lifo.new()
    ipLifo1.pushEmpty(fuel_map_lcm_name, "LCM") # Fuel Map
    ipLifo1.pushEmpty(matex_lcm_name, "LCM") # Material Indexation
    ipLifo1.pushEmpty(track_lcm_name, "LCM") # Tracking data for FEM
    for compo_lcm_name in compo_lcm_names:
        ipLifo1.pushEmpty(compo_lcm_name, "LCM") # Compo
    for compo_file_name in compo_file_names:
        ipLifo1.push(compo_file_name) # Compo name

    # 3.2) call IniDONJON Cle-2000 procedure
    IniDONJON = cle2000.new(init_c2m_name,ipLifo1,1)
    IniDONJON.exec()
    print(f"procedure {init_c2m_name} execution completed")

    # recover the output LCM objects
    compos = []
    Fmap = ipLifo1.node(fuel_map_lcm_name)
    Matex = ipLifo1.node(matex_lcm_name)
    Track = ipLifo1.node(track_lcm_name)
    for compo_lcm_name in compo_lcm_names:
        compos.append(ipLifo1.node(compo_lcm_name))

    # empty the Lifo stack for IniDONJON
    while ipLifo1.getMax() > 0:
        ipLifo1.pop()

    return Fmap, Matex, Track, compos

def neutronics_solution(procedure_names, iteration, Fmap, Matex, THData, Track, Flux, Cpos):
    """
    Execute donjon procecdure providing the neutronics solution : interpolate cross sections at
    """
    ################## Neutronics part ##################
    # fill the Lifo stack for Neutronics solution
    print(f"$$ - BEGIN iter = {iteration}")
    ipLifoN = lifo.new()
    ipLifoN.push(Fmap) # Fuel map
    ipLifoN.push(Matex) # Material indexation
    if iteration > 1:
        ipLifoN.push(Flux) # Neutron flux distribution
    else:
        ipLifoN.pushEmpty("Flux", "LCM")
    ipLifoN.pushEmpty("Power", "LCM") # Power distribution : to store output Power distributio
    ipLifoN.push(Track) # FEM numbering and mesh to be used in TRIVAC:
    ipLifoN.push(THData)
    for Cpo in Cpos:
        ipLifoN.push(Cpo) # MULTICOMPO to read XS from
    ipLifoN.push(iteration) # Iteration number

    # 4.2) Call Neutronics component :
    print("call Neutronics procedure at iter=", iteration)
    Neutronics = cle2000.new(procedure_names["neutronics_solve"],ipLifoN,1)
    Neutronics.exec()
    # Get the results
    Fmap = ipLifoN.node("Fmap")
    Matex = ipLifoN.node("Matex")
    Track = ipLifoN.node("Track")
    Power = ipLifoN.node("Power")
    Flux = ipLifoN.node("Flux")

    # empty the Lifo stack for solNeutro
    while ipLifoN.getMax() > 0:
        ipLifoN.pop()

    return Power, Flux, Fmap, Matex, Track
