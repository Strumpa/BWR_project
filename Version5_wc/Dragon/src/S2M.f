*DECK S2M
      SUBROUTINE S2M(NENTRY,HENTRY,IENTRY,JENTRY,KENTRY)
*
*-----------------------------------------------------------------------
*
*Purpose:
*  To recover information from a SERPENT output file and translate the
*  requested data towards a macrolib.
*
*Copyright:
* Copyright (C) 2014 Ecole Polytechnique de Montreal
* This library is free software; you can redistribute it and/or
* modify it under the terms of the GNU Lesser General Public
* License as published by the Free Software Foundation; either
* version 2.1 of the License, or (at your option) any later version
*
*Author(s): A. Hebert and C. Bienvenue
*
*Parameters: input/output
* NENTRY  number of LCM objects or files used by the operator.
* HENTRY  name of each LCM object or file:
*         HENTRY(1) create or modification ascii file containing
*         Apotrim data;
*         HENTRY(2) read-only type(L_MACROLIB).
* IENTRY  type of each LCM object or file:
*         =1 LCM memory object; =2 XSM file; =3 sequential binary file;
*         =4 sequential ascii file.
* JENTRY  access of each LCM object or file:
*         =0 the LCM object or file is created;
*         =1 the LCM object or file is open for modifications;
*         =2 the LCM object or file is open in read-only mode.
* KENTRY  LCM object address or file unit number.
*
*-----------------------------------------------------------------------
*
      USE GANLIB
*----
*  SUBROUTINE ARGUMENTS
*----
      INTEGER      NENTRY,IENTRY(NENTRY),JENTRY(NENTRY)
      TYPE(C_PTR)  KENTRY(NENTRY)
      CHARACTER    HENTRY(NENTRY)*12
*----
*  LOCAL VARIABLES
*----
      TYPE(C_PTR) IPMAC,JPMAC,KPMAC
      PARAMETER (NSTATE=40,IOUT=6)
      CHARACTER TEXT12*12,HSIGN*12,HLINE*512,CM*2,HSMG*131
      CHARACTER HVERS*24,HNGRP*26,HBOUND*26,HTOT*26,HFLUX*26,HSCAT*26,
     > HCHI*26,HNSF*26,HDIFF*26
      LOGICAL LB1,LFIS,LFOUND
      DOUBLE PRECISION DFLOTT
      INTEGER ISTATE(NSTATE)
      PARAMETER(CM='00')
*----
*  ALLOCATABLE ARRAYS
*----
      REAL, ALLOCATABLE, DIMENSION(:) :: XS,FLUX,FISS,CHI,DIFF,GAR3
      REAL, ALLOCATABLE, DIMENSION(:,:) :: SCAT
*
      IF(NENTRY.LE.1) CALL XABORT('S2M: MINIMUM OF 2 OBJECTS EXPECTED.')
      TEXT12=HENTRY(1)
      IF((IENTRY(1).NE.1).AND.(IENTRY(1).NE.4)) CALL XABORT('S2M: LCM '
     1 //'OBJECT EXPECTED AT LHS.')
      IF(JENTRY(1).EQ.2) CALL XABORT('S2M: LCM OBJECT IN CREATE OR MOD'
     1 //'IFICATION MODE EXPECTED AT LHS.')
      IPMAC=KENTRY(1)
      IF(IENTRY(2).NE.4) CALL XABORT('S2M: ASCII FILE NAMED '//TEXT12
     1 //' EXPECTED AT RHS.')
      IF(JENTRY(2).NE.2) CALL XABORT('S2M: ASCII FILE IN READ-ONLY MOD'
     1 //'E EXPECTED AT RHS.')
      IFIN=FILUNIT(KENTRY(2))
      HSIGN='L_MACROLIB'
      CALL LCMPTC(IPMAC,'SIGNATURE',12,HSIGN)
*----
*  READ THE INPUT DATA
*----
      IMPX=1
      IDX=1
      NGRP=0
      HVERS=' '
      EMAX=2.0E7
      EMIN=1.0E-5
      LB1=.FALSE.
   20 CALL REDGET(INDIC,NITMA,FLOTT,TEXT12,DFLOTT)
      IF(INDIC.NE.3) CALL XABORT('S2M: CHARACTER DATA EXPECTED(1).')
      IF(TEXT12.EQ.'EDIT') THEN
*        READ THE PRINT INDEX.
         CALL REDGET(INDIC,IMPX,FLOTT,TEXT12,DFLOTT)
         IF(INDIC.NE.1) CALL XABORT('S2M: INTEGER DATA EXPECTED(1).')
      ELSE IF(TEXT12.EQ.'IDX') THEN
*        READ THE INSTANCE INDEX.
         CALL REDGET(INDIC,IDX,FLOTT,TEXT12,DFLOTT)
         IF(INDIC.NE.1) CALL XABORT('S2M: INTEGER DATA EXPECTED(2).')
         IF(IDX.LE.0) CALL XABORT('S2M: INVALID VALUE OF IDX.')
      ELSE IF(TEXT12.EQ.'EMAX') THEN
*        READ THE UPPER ENERGY LIMIT IN EV.
         CALL REDGET(INDIC,NITMA,EMAX,TEXT12,DFLOTT)
         IF(INDIC.NE.2) CALL XABORT('S2M: REAL DATA EXPECTED(1).')
         IF(EMAX.LE.0.0) CALL XABORT('S2M: INVALID VALUE OF EMAX.')
      ELSE IF(TEXT12.EQ.'EMIN') THEN
*        READ THE LOWER ENERGY LIMIT IN EV.
         CALL REDGET(INDIC,NITMA,EMIN,TEXT12,DFLOTT)
         IF(INDIC.NE.2) CALL XABORT('S2M: REAL DATA EXPECTED(2).')
         IF(EMIN.LE.0.0) CALL XABORT('S2M: INVALID VALUE OF EMIN.')
      ELSE IF(TEXT12.EQ.'B1') THEN
         LB1=.TRUE.
      ELSE IF(TEXT12.EQ.';') THEN
         GO TO 30
      ELSE
         CALL XABORT('S2M: '//TEXT12//' IS AN INVALID KEYWORD.')
      ENDIF
      GO TO 20
   30 IF(EMIN.GE.EMAX) CALL XABORT('S2M: EMIN.GE.EMAX.')
*----
*  IDENTIFY THE SERPENT RECORD NAMING CONVENTION
*----
*     THE GROUP-STRUCTURE RECORD IS THE DISCRIMINANT: MACRO_NG IS WRITTEN
*     BY SERPENT >= 2.1.19 AND GC_NE BY EARLIER VERSIONS. THIS IS A MORE
*     DIRECT TEST THAN THE VERSION RECORD, WHICH IS ABSENT FROM POST-
*     PROCESSED FILES AND SAYS NOTHING ON THE RECORDS ACTUALLY PRESENT.
      CALL S2MHAS('MACRO_NG',LFOUND)
      IF(LFOUND) THEN
         IVERS=2
      ELSE
         CALL S2MHAS('GC_NE',LFOUND)
         IF(LFOUND) THEN
            IVERS=1
         ELSE
            CALL XABORT('S2M: NEITHER THE MACRO_NG NOR THE GC_NE RECORD'
     1      //' WAS FOUND. THIS IS NOT A SERPENT _res.m FILE.')
         ENDIF
      ENDIF
*     RECOVER THE SERPENT VERSION NUMBER, FOR PRINTOUT PURPOSES ONLY.
      REWIND(IFIN)
      DO
        READ(IFIN,'(A)',END=40) HLINE
        IF(HLINE(:8).EQ.'VERSION ') THEN
           IND1=INDEX(HLINE,'''')
           IF(IND1.GT.0) THEN
              IND2=IND1+INDEX(HLINE(IND1+1:),'''')
              IF(IND2.GT.IND1+1) HVERS=HLINE(IND1+1:IND2-1)
           ENDIF
           GO TO 40
        ENDIF
      ENDDO
   40 CONTINUE
*----
*  SET THE SERPENT RECORD NAMES
*----
      IF(IVERS.EQ.1) THEN
*        SERPENT <= 2.1.18.
         HNGRP='GC_NE'
         HBOUND='GC_BOUNDS'
         HTOT='TOTXS'
         HFLUX='FLUX'
         HSCAT='GTRANSFXS'
         HCHI='CHI'
         HNSF='NSF'
         NEXTRA=1
      ELSE
*        SERPENT >= 2.1.19.
         HNGRP='MACRO_NG'
         HBOUND='MACRO_E'
         IF(LB1) THEN
            HTOT='B1_TOT'
            HFLUX='B1_FLX'
            HSCAT='B1_SP0'
            HCHI='B1_CHIT'
            HNSF='B1_NSF'
         ELSE
            HTOT='INF_TOT'
            HFLUX='INF_FLX'
            HSCAT='INF_SP0'
            HCHI='INF_CHIT'
            HNSF='INF_NSF'
         ENDIF
         NEXTRA=0
      ENDIF
      HDIFF='B1_DIFFCOEF'
      IF(IMPX.GT.0) THEN
         IF(HVERS.EQ.' ') HVERS='UNKNOWN'
         WRITE(IOUT,100) TRIM(HVERS),IVERS
      ENDIF
*----
*  FIND THE NUMBER OF ENERGY GROUPS
*----
      REWIND(IFIN)
      DO
        READ(IFIN,'(A)',END=50) HLINE
        IF(HLINE(:26).EQ.HNGRP) THEN
           IND1=INDEX(HLINE,'=')
           IND2=INDEX(HLINE,';')
           IF((IND1.EQ.0).OR.(IND2.LE.IND1)) GO TO 50
           READ(HLINE(IND1+1:IND2-1),*,IOSTAT=IOS) NGRP
           IF(IOS.NE.0) GO TO 50
           GO TO 60
        ENDIF
      ENDDO
   50 CALL XABORT('S2M: UNABLE TO FIND THE NUMBER OF ENERGY GROUPS ON '
     1 //'THE '//TRIM(HNGRP)//' RECORD.')
   60 IF(NGRP.LE.0) CALL XABORT('S2M: INVALID NUMBER OF ENERGY GROUPS.')
      IF(IMPX.GT.0) WRITE(IOUT,110) NGRP
*----
*  RECOVER CROSS SECTIONS
*----
      ALLOCATE(XS(NGRP+1),FLUX(NGRP+1),CHI(NGRP),FISS(NGRP+1),
     > SCAT(NGRP,NGRP),DIFF(NGRP),GAR3(NGRP*NGRP))
*----
*  ENERGY GROUP BOUNDARIES. SERPENT USES MEV AND MAY SET THE OUTER
*  BOUNDARIES TO 1.0E37 AND 0.0; DRAGON EXPECTS DECREASING FINITE
*  BOUNDARIES IN EV.
*----
      CALL S2MGET(IFIN,HBOUND,IDX,.FALSE.,NGRP+1,XS(1))
      DO IGRP=1,NGRP+1
        XS(IGRP)=XS(IGRP)*1.0E6
      ENDDO
      IF(XS(1).LT.XS(NGRP+1)) THEN
*        REORDER TOWARDS DECREASING ENERGIES.
         DO IGRP=1,(NGRP+1)/2
           FLOTT=XS(IGRP)
           XS(IGRP)=XS(NGRP+2-IGRP)
           XS(NGRP+2-IGRP)=FLOTT
         ENDDO
      ENDIF
      DO IGRP=1,NGRP+1
        IF(XS(IGRP).GT.EMAX) XS(IGRP)=EMAX
        IF(XS(IGRP).LT.EMIN) XS(IGRP)=EMIN
      ENDDO
      DO IGRP=1,NGRP
        IF(XS(IGRP).LE.XS(IGRP+1)) THEN
           WRITE(HSMG,'(''S2M: THE ENERGY MESH IS NOT DECREASING AT '',
     1     ''GROUP '',I5,''.'')') IGRP
           CALL XABORT(HSMG)
        ENDIF
      ENDDO
      CALL LCMPUT(IPMAC,'ENERGY',NGRP+1,2,XS)
*----
*  DETERMINE IF THE MIXTURE IS FISSILE
*----
      LFIS=.FALSE.
      CALL S2MHAS(HNSF,LFOUND)
      IF(LFOUND) THEN
         CALL S2MGET(IFIN,HNSF,IDX,.TRUE.,NGRP+NEXTRA,FISS(1))
         DO IGRP=1,NGRP
           IF(FISS(IGRP+NEXTRA).NE.0.0) LFIS=.TRUE.
         ENDDO
      ENDIF
      IF(IMPX.GT.0) WRITE(IOUT,120) LFIS
*----
*  REMAINING CROSS SECTIONS
*----
      CALL S2MGET(IFIN,HTOT,IDX,.TRUE.,NGRP+NEXTRA,XS(1))
      CALL S2MGET(IFIN,HFLUX,IDX,.TRUE.,NGRP+NEXTRA,FLUX(1))
      CALL S2MGET(IFIN,HSCAT,IDX,.TRUE.,NGRP*NGRP,SCAT(1,1))
*     SCAT IS FILLED IN COLUMN-MAJOR ORDER FROM A ROW-MAJOR SERPENT
*     MATRIX PRINTED WITH THE INITIAL GROUP AS THE OUTER INDEX, HENCE
*     SCAT(JGRP,IGRP) IS SIGMA(IGRP -> JGRP).
      IF(LFIS) CALL S2MGET(IFIN,HCHI,IDX,.TRUE.,NGRP,CHI(1))
      IF(LB1) CALL S2MGET(IFIN,HDIFF,IDX,.TRUE.,NGRP,DIFF(1))
      JPMAC=LCMLID(IPMAC,'GROUP',NGRP)
      DO IGRP=1,NGRP
        KPMAC=LCMDIL(JPMAC,IGRP)
        CALL LCMPUT(KPMAC,'NTOT0',1,2,XS(IGRP+NEXTRA))
        CALL LCMPUT(KPMAC,'NWT0',1,2,FLUX(IGRP+NEXTRA))
        IF(LFIS) THEN
          CALL LCMPUT(KPMAC,'CHI',1,2,CHI(IGRP))
          CALL LCMPUT(KPMAC,'NUSIGF',1,2,FISS(IGRP+NEXTRA))
        ENDIF
        IF(LB1) THEN
          CALL LCMPUT(KPMAC,'DIFF',1,2,DIFF(IGRP))
        ENDIF
        IPOSDE=0
        IPOS=1
        IGMIN=IGRP
        IGMAX=IGRP
*       /GROUP/IGRP HOLDS THE SECONDARY (ARRIVAL) GROUP SLICE, I.E. THE
*       SIGMA(JGRP -> IGRP) = SCAT(IGRP,JGRP) COMPONENTS.
        DO JGRP=1,NGRP
          IF(SCAT(IGRP,JGRP).NE.0.0) THEN
            IGMIN=MIN(IGMIN,JGRP)
            IGMAX=MAX(IGMAX,JGRP)
          ENDIF
        ENDDO
        IJJ=IGMAX
        NJJ=IGMAX-IGMIN+1
        DO JGRP=IGMAX,IGMIN,-1
          IPOSDE=IPOSDE+1
          GAR3(IPOSDE)=SCAT(IGRP,JGRP)
        ENDDO
*       TOTAL SCATTERING CROSS SECTION OUT OF GROUP IGRP.
        SIGS=0.0
        DO JGRP=1,NGRP
          SIGS=SIGS+SCAT(JGRP,IGRP)
        ENDDO
        CALL LCMPUT(KPMAC,'SCAT'//CM,IPOSDE,2,GAR3)
        CALL LCMPUT(KPMAC,'SIGW'//CM,1,2,SCAT(IGRP,IGRP))
        CALL LCMPUT(KPMAC,'SIGS'//CM,1,2,SIGS)
        CALL LCMPUT(KPMAC,'NJJS'//CM,1,1,NJJ)
        CALL LCMPUT(KPMAC,'IJJS'//CM,1,1,IJJ)
        CALL LCMPUT(KPMAC,'IPOS'//CM,1,1,IPOS)
      ENDDO
      ISTATE(:NSTATE)=0
      ISTATE(1)=NGRP
      ISTATE(2)=1
      ISTATE(3)=1
      IF(LFIS) ISTATE(4)=1
      IF(LB1) ISTATE(9)=1
      CALL LCMPUT(IPMAC,'STATE-VECTOR',NSTATE,1,ISTATE)
      DEALLOCATE(GAR3,DIFF,SCAT,FISS,CHI,FLUX,XS)
      RETURN
*
  100 FORMAT(/' S2M: SERPENT FILE VERSION= ',A,
     1 ' ; NAMING CONVENTION= ',I2,' (1=LEGACY, 2=SINCE 2.1.19).')
  110 FORMAT(' S2M: NUMBER OF ENERGY GROUPS=',I5)
  120 FORMAT(' S2M: FISSILE FLAG=',L1)
*
      CONTAINS
*
      SUBROUTINE S2MHAS(HNAME,LOK)
*----
*  Set LOK to .TRUE. if a record named HNAME is present on unit IFIN.
*  The record name is blank-padded on a 26-character field, so that
*  INF_TOT is not confused with INF_TRANSPXS.
*----
      CHARACTER*(*) HNAME
      LOGICAL LOK
      CHARACTER HREC*26,HTST*26
*
      LOK=.FALSE.
      IF(LEN(HNAME).GT.26) CALL XABORT('S2MHAS: PREFIX OVERFLOW.')
      HTST=HNAME
      REWIND(IFIN)
      DO
        READ(IFIN,'(A26)',END=10) HREC
        IF(HREC.EQ.HTST) THEN
          LOK=.TRUE.
          RETURN
        ENDIF
      ENDDO
   10 RETURN
      END SUBROUTINE S2MHAS
*
      END
